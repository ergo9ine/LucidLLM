/**
 * [Lucid] i18n 키 레지스트리의 정합성을 검증합니다.
 * 중복된 값이나 잘못된 형식의 키가 있는지 확인합니다.
 */
export function validateI18nRegistry() {
    const values = Object.values(I18N_KEYS);
    const seen = new Map(); // value -> key
    const duplicates = [];

    for (const [key, value] of Object.entries(I18N_KEYS)) {
        if (seen.has(value)) {
            duplicates.push({ value, originalKey: seen.get(value), duplicateKey: key });
        } else {
            seen.set(value, key);
        }

        // 단순 형식 검사 (소문자, 숫자, 점, 언더스코어만 허용)
        if (!/^[a-z0-9._-]+$/.test(value)) {
            console.warn(`[I18N] Invalid value format for key "${key}": "${value}"`);
        }
    }

    if (duplicates.length > 0) {
        console.error("[I18N] Duplicate translation values detected in I18N_KEYS:", duplicates);
        return false;
    }

    return true;
}

// 로컬 개발 환경에서 자동 실행
if (typeof window !== "undefined") {
    const host = window.location.hostname;
    if (host === "localhost" || host === "127.0.0.1" || host.startsWith("192.168.")) {
        validateI18nRegistry();
    }
}
